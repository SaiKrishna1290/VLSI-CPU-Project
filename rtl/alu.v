`timescale 1ns/1ps

module alu (
    input  [7:0] a,
    input  [7:0] b,
    input  [3:0] sel,

    output reg [7:0] y,
    output reg       zero,
    output reg       carry,
    output reg       overflow,
    output reg       div_zero
);

reg [8:0] temp;

always @(*) begin

    // Default values
    y        = 8'b00000000;
    carry    = 1'b0;
    overflow = 1'b0;
    div_zero = 1'b0;
    temp     = 9'b000000000;

    case (sel)

        // ---------------------------------
        // 0000 : ADD
        // ---------------------------------
        4'b0000: begin
            temp = a + b;
            y = temp[7:0];
            carry = temp[8];

            overflow =
                (~(a[7] ^ b[7])) &
                (a[7] ^ y[7]);
        end

        // ---------------------------------
        // 0001 : SUBTRACT
        // ---------------------------------
        4'b0001: begin
            y = a - b;

            overflow =
                (a[7] ^ b[7]) &
                (a[7] ^ y[7]);
        end

        // ---------------------------------
        // 0010 : AND
        // ---------------------------------
        4'b0010: begin
            y = a & b;
        end

        // ---------------------------------
        // 0011 : OR
        // ---------------------------------
        4'b0011: begin
            y = a | b;
        end

        // ---------------------------------
        // 0100 : XOR
        // ---------------------------------
        4'b0100: begin
            y = a ^ b;
        end

        // ---------------------------------
        // 0101 : NOT A
        // ---------------------------------
        4'b0101: begin
            y = ~a;
        end

        // ---------------------------------
        // 0110 : INCREMENT A
        // ---------------------------------
        4'b0110: begin
            temp = a + 1'b1;
            y = temp[7:0];
            carry = temp[8];
        end

        // ---------------------------------
        // 0111 : DECREMENT A
        // ---------------------------------
        4'b0111: begin
            y = a - 1'b1;
        end

        // ---------------------------------
        // 1000 : A EQUAL TO B
        // Result = 1 if true
        // ---------------------------------
        4'b1000: begin
            if (a == b)
                y = 8'b00000001;
            else
                y = 8'b00000000;
        end

        // ---------------------------------
        // 1001 : A GREATER THAN B
        // ---------------------------------
        4'b1001: begin
            if (a > b)
                y = 8'b00000001;
            else
                y = 8'b00000000;
        end

        // ---------------------------------
        // 1010 : A LESS THAN B
        // ---------------------------------
        4'b1010: begin
            if (a < b)
                y = 8'b00000001;
            else
                y = 8'b00000000;
        end

        // ---------------------------------
        // 1011 : A NOT EQUAL TO B
        // ---------------------------------
        4'b1011: begin
            if (a != b)
                y = 8'b00000001;
            else
                y = 8'b00000000;
        end

        // ---------------------------------
        // 1100 : MULTIPLICATION
        // ---------------------------------
        4'b1100: begin
            y = a * b;
        end

        // ---------------------------------
        // 1101 : DIVISION
        // ---------------------------------
        4'b1101: begin
            if (b == 8'b00000000) begin
                y = 8'b00000000;
                div_zero = 1'b1;
            end
            else begin
                y = a / b;
            end
        end

        // ---------------------------------
        // 1110 : LEFT SHIFT
        // ---------------------------------
        4'b1110: begin
            y = a << 1;
        end

        // ---------------------------------
        // 1111 : RIGHT SHIFT
        // ---------------------------------
        4'b1111: begin
            y = a >> 1;
        end

        default: begin
            y = 8'b00000000;
        end

    endcase

    // Zero Flag
    if (y == 8'b00000000)
        zero = 1'b1;
    else
        zero = 1'b0;

end

endmodule