`timescale 1ns/1ps

module alu_tb;

    // Inputs
    reg [7:0] a;
    reg [7:0] b;
    reg [3:0] sel;

    // Outputs
    wire [7:0] y;
    wire zero;
    wire carry;
    wire overflow;
    wire div_zero;

    // ---------------------------------
    // Instantiate ALU
    // ---------------------------------

    alu uut (
        .a(a),
        .b(b),
        .sel(sel),
        .y(y),
        .zero(zero),
        .carry(carry),
        .overflow(overflow),
        .div_zero(div_zero)
    );


    initial begin

        // ---------------------------------
        // Initialize
        // ---------------------------------

        a = 0;
        b = 0;
        sel = 0;

        #10;


        // =================================
        // ADDITION
        // 10 + 5 = 15
        // =================================

        a = 8'd10;
        b = 8'd5;
        sel = 4'b0000;

        #10;


        // =================================
        // SUBTRACTION
        // 10 - 5 = 5
        // =================================

        a = 8'd10;
        b = 8'd5;
        sel = 4'b0001;

        #10;


        // =================================
        // AND
        // =================================

        a = 8'b11001100;
        b = 8'b10101010;
        sel = 4'b0010;

        #10;


        // =================================
        // OR
        // =================================

        a = 8'b11001100;
        b = 8'b10101010;
        sel = 4'b0011;

        #10;


        // =================================
        // XOR
        // =================================

        a = 8'b11001100;
        b = 8'b10101010;
        sel = 4'b0100;

        #10;


        // =================================
        // NOT
        // =================================

        a = 8'b00001111;
        b = 8'b00000000;
        sel = 4'b0101;

        #10;


        // =================================
        // INCREMENT
        // 10 + 1 = 11
        // =================================

        a = 8'd10;
        b = 8'd0;
        sel = 4'b0110;

        #10;


        // =================================
        // DECREMENT
        // 10 - 1 = 9
        // =================================

        a = 8'd10;
        b = 8'd0;
        sel = 4'b0111;

        #10;


        // =================================
        // EQUAL COMPARISON
        // =================================

        a = 8'd10;
        b = 8'd10;
        sel = 4'b1000;

        #10;


        // =================================
        // GREATER THAN
        // 15 > 10
        // =================================

        a = 8'd15;
        b = 8'd10;
        sel = 4'b1001;

        #10;


        // =================================
        // LESS THAN
        // 5 < 10
        // =================================

        a = 8'd5;
        b = 8'd10;
        sel = 4'b1010;

        #10;


        // =================================
        // NOT EQUAL
        // =================================

        a = 8'd10;
        b = 8'd5;
        sel = 4'b1011;

        #10;


        // =================================
        // MULTIPLICATION
        // 5 * 4 = 20
        // =================================

        a = 8'd5;
        b = 8'd4;
        sel = 4'b1100;

        #10;


        // =================================
        // DIVISION
        // 20 / 4 = 5
        // =================================

        a = 8'd20;
        b = 8'd4;
        sel = 4'b1101;

        #10;


        // =================================
        // DIVISION BY ZERO
        // =================================

        a = 8'd20;
        b = 8'd0;
        sel = 4'b1101;

        #10;


        // =================================
        // LEFT SHIFT
        // =================================

        a = 8'b00000101;
        b = 8'b0;
        sel = 4'b1110;

        #10;


        // =================================
        // RIGHT SHIFT
        // =================================

        a = 8'b00010100;
        b = 8'b0;
        sel = 4'b1111;

        #10;


        // Finish simulation
        $finish;

    end

endmodule